import pytest

from autocontribute.ai_policy import (
    AiPolicyQuote,
    PolicyFile,
    RepositoryAiPolicy,
    ai_policy_digest,
    ai_policy_files,
    checked_ai_policy,
    deterministic_ai_policy,
)


def _policy(text: str, path: str = "docs/notes.md") -> RepositoryAiPolicy:
    return deterministic_ai_policy([PolicyFile("example/project", path, text)])


@pytest.mark.parametrize(
    ("path", "text"),
    [
        # pytest
        ("CONTRIBUTING.rst", "Purely agentic contributions are not accepted."),
        (
            ".github/PULL_REQUEST_TEMPLATE.md",
            "Unsupervised agentic contributions are not accepted.",
        ),
        ("CONTRIBUTING.rst", "Pull requests generated by AI agents will be closed."),
        # Astral
        ("AI_POLICY.md", "We do not allow autonomous agents to be used for contributing."),
        # scikit-learn
        (
            "doc/developers/contributing.rst",
            "Please refrain from submitting issues or pull requests generated by fully-automated "
            "tools.",
        ),
        # QEMU, reached through a link from its contribution guide
        (
            "docs/devel/code-provenance.rst",
            "Current QEMU project policy is to DECLINE any contributions which are believed to\n"
            "include or derive from AI generated content.",
        ),
        (
            "docs/devel/code-provenance.rst",
            "Contributors must refrain from using AI content generators on patches.",
        ),
        # Godot
        ("CONTRIBUTING.md", "Autonomous agents and vibe coding lead to an auto-ban."),
        # misses of the old patterns
        ("docs/notes.md", "Contributions written with LLMs are not accepted."),
        ("docs/notes.md", "Pull requests authored by Copilot, Claude, or ChatGPT will be closed."),
        (
            "docs/notes.md",
            "We take AI-assisted contributions, but no unsupervised agentic tools like OpenClaw.",
        ),
        ("docs/notes.md", "Machine-generated pull requests will be closed."),
        # emphasis and HTML comments
        ("CONTRIBUTING.md", "**Agentic** contributions are _not accepted_."),
        ("CONTRIBUTING.md", "<!-- Pull requests from AI agents will be closed. -->"),
        ("CONTRIBUTING.md", "Pull requests from AI agents won\u2019t be accepted."),
    ],
)
def test_ban_grammar_finds_published_bans(path: str, text: str) -> None:
    policy = _policy(text, path)

    assert policy.stance == "ban"
    assert all(quote.text in text for quote in policy.quotes)


@pytest.mark.parametrize(
    ("path", "text"),
    [
        ("CONTRIBUTING.md", "Do not edit generated code by hand."),
        (".github/PULL_REQUEST_TEMPLATE.md", "- [ ] No AI tools used"),
        (".github/PULL_REQUEST_TEMPLATE.md", "- [ ] No AI-generated code"),
        ("CONTRIBUTING.md", "Do not skip the automated tests."),
        ("CONTRIBUTING.md", "There is no need to run the automated formatter."),
        ("CONTRIBUTING.md", "We don't use bots for releases."),
        ("docs/README.md", "You don't need a bot to build the docs preview."),
        # fastapi: about security reports, not pull requests
        ("SECURITY.md", "AI-generated security reports that were not verified will be closed."),
        # curl
        ("docs/CONTRIBUTE.md", "We accept no unlicensed code. This is independent if AI was used."),
        # LLVM reserves good first issues for people; that is a label rule, not a ban
        (
            "docs/AIToolPolicy.md",
            "Using AI tools to fix issues labelled as 'good first issues' is forbidden.",
        ),
        ("CONTRIBUTING.md", "AI-generated code is welcome, but untested pull requests are closed."),
    ],
)
def test_ban_grammar_ignores_known_false_positives(path: str, text: str) -> None:
    assert _policy(text, path).stance != "ban"


@pytest.mark.parametrize(
    "text",
    [
        "Please do not use AI to write your PR description.",
        # numpy
        "Please do not use AI to automatically generate pull request descriptions.",
        # pandas
        "You must not use AI to speak for you.",
        # matplotlib
        "Describe your change in your own words (no AI please).",
    ],
)
def test_human_written_text_rules_are_conditions(text: str) -> None:
    policy = _policy(text, "CONTRIBUTING.md")

    assert policy.stance == "conditional"
    assert policy.requires_human_written_text
    assert [quote.text for quote in policy.quotes] == [text]


def test_disclosure_rules_are_conditions_with_their_requirements() -> None:
    text = (
        "Contributors must read and review all LLM-generated code before asking for review.\n\n"
        "Add an `Assisted-by: <name of code assistant>` trailer. Disclose any AI use in the "
        "pull request."
    )

    policy = _policy(text, "docs/AIToolPolicy.md")

    assert policy.stance == "conditional"
    assert policy.requires_disclosure
    assert not policy.requires_human_written_text
    assert policy.disclosure_requirements == [
        "Add an `Assisted-by: <name of code assistant>` trailer.",
        "Disclose any AI use in the pull request.",
    ]


def test_policy_without_ai_rules_has_no_stance() -> None:
    assert _policy("Run the tests before opening a pull request.") == RepositoryAiPolicy(
        stance="none"
    )


def test_sentences_never_span_two_files() -> None:
    files = [
        PolicyFile("example/project", "CONTRIBUTING.md", "Agentic tools help us triage"),
        PolicyFile("example/project", "SUPPORT.md", "contributions are not accepted by email."),
    ]

    assert deterministic_ai_policy(files).stance == "none"


def test_ban_quotes_are_verbatim_and_name_their_file() -> None:
    text = "Intro.\n\nAI-generated pull requests\nwill be closed.\n\nOutro."

    policy = deterministic_ai_policy([PolicyFile("example/.github", "AI_POLICY.md", text)])

    assert policy.quotes == [
        AiPolicyQuote(
            repository="example/.github",
            path="AI_POLICY.md",
            text="AI-generated pull requests\nwill be closed.",
        )
    ]


def test_classifier_input_is_files_that_mention_ai_and_agent_instructions() -> None:
    files = [
        PolicyFile("example/project", "CONTRIBUTING.md", "Run the tests."),
        PolicyFile("example/project", "AGENTS.md", "Use uv to run the tests."),
        PolicyFile("example/project", "SECURITY.md", "Reports written with an LLM are welcome."),
    ]

    assert [file.path for file in ai_policy_files(files)] == ["AGENTS.md", "SECURITY.md"]


def test_digest_changes_with_any_file_and_ignores_order() -> None:
    first = PolicyFile("example/project", "AI_POLICY.md", "AI use must be disclosed.")
    second = PolicyFile("example/project", "AGENTS.md", "Use uv.")

    assert ai_policy_digest([first, second]) == ai_policy_digest([second, first])
    assert ai_policy_digest([first]) != ai_policy_digest(
        [PolicyFile("example/project", "AI_POLICY.md", "AI use must be disclosed in the PR.")]
    )


_FILES = [
    PolicyFile(
        "example/project",
        "AI_POLICY.md",
        "AI-assisted work is welcome.\nAutonomous agents may not open\npull requests here.",
    )
]
_FALLBACK = RepositoryAiPolicy(stance="none")


def test_verified_classifier_reading_is_kept() -> None:
    claimed = RepositoryAiPolicy(
        stance="ban",
        quotes=[
            AiPolicyQuote(
                repository="Example/Project",
                path="AI_POLICY.md",
                # Line breaks in the file may be quoted as spaces.
                text="Autonomous agents may not open pull requests here.",
            )
        ],
    )

    assert checked_ai_policy(claimed, _FILES, fallback=_FALLBACK) == claimed


@pytest.mark.parametrize(
    "quote",
    [
        AiPolicyQuote(repository="example/project", path="AI_POLICY.md", text="Agents are banned."),
        AiPolicyQuote(
            repository="example/project",
            path="CONTRIBUTING.md",
            text="Autonomous agents may not open",
        ),
        AiPolicyQuote(repository="example/project", path="AI_POLICY.md", text="  "),
    ],
)
def test_unverified_ban_becomes_unclear(quote: AiPolicyQuote) -> None:
    claimed = RepositoryAiPolicy(stance="ban", quotes=[quote])

    assert checked_ai_policy(claimed, _FILES, fallback=_FALLBACK) == RepositoryAiPolicy(
        stance="unclear"
    )


def test_ban_without_quotes_becomes_unclear() -> None:
    checked = checked_ai_policy(RepositoryAiPolicy(stance="ban"), _FILES, fallback=_FALLBACK)

    assert checked.stance == "unclear"


def test_unverified_conditional_reading_gives_way_to_the_deterministic_one() -> None:
    claimed = RepositoryAiPolicy(
        stance="conditional",
        requires_human_written_text=True,
        quotes=[
            AiPolicyQuote(
                repository="example/project",
                path="AI_POLICY.md",
                text="Write the description yourself.",
            )
        ],
    )

    assert checked_ai_policy(claimed, _FILES, fallback=_FALLBACK) == _FALLBACK


def test_permissive_reading_needs_no_quotes() -> None:
    claimed = RepositoryAiPolicy(stance="permissive")

    assert checked_ai_policy(claimed, _FILES, fallback=_FALLBACK) == claimed
